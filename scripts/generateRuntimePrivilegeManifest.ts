/**
 * Builds src/config/runtimePrivileges.generated.json: every table privilege and every app_* function the
 * runtime code (src/, tests excluded) uses. The backend checks at startup that app_runtime holds all of them,
 * so a missing GRANT is visible in the logs BEFORE production switches from postgres to app_runtime.
 *
 *   npx tsx scripts/generateRuntimePrivilegeManifest.ts          # rewrite the manifest
 *   npx tsx scripts/generateRuntimePrivilegeManifest.ts --check  # exit 1 if it is out of date (unit test)
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const OUT = join(ROOT, "src/config/runtimePrivileges.generated.json");

function files(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) return files(p);
    return p.endsWith(".ts") && !p.includes(".test.") ? [p] : [];
  });
}

const PATTERNS: Array<[RegExp, "SELECT" | "INSERT" | "UPDATE" | "DELETE"]> = [
  [/\b(?:FROM|JOIN)\s+(?:public\.)?([a-z_][a-z0-9_]+)\b/g, "SELECT"],
  [/\bINSERT\s+INTO\s+(?:public\.)?([a-z_][a-z0-9_]+)/g, "INSERT"],
  [/\bUPDATE\s+(?:public\.)?([a-z_][a-z0-9_]+)\s+(?:[a-z]+\s+)?SET\b/g, "UPDATE"],
  [/\bDELETE\s+FROM\s+(?:public\.)?([a-z_][a-z0-9_]+)/g, "DELETE"],
  [/selectFrom\(\s*["']([a-z_]+)/g, "SELECT"],
  [/insertInto\(\s*["']([a-z_]+)/g, "INSERT"],
  [/updateTable\(\s*["']([a-z_]+)/g, "UPDATE"],
  [/deleteFrom\(\s*["']([a-z_]+)/g, "DELETE"],
];
// Words the SQL patterns catch that are not tables (functions, CTEs, set-returning calls, keywords).
const NOT_TABLES = new Set(["unnest", "generate_series", "jsonb_array_elements", "jsonb_each", "lateral", "only", "pg_stat_activity", "pg_roles", "pg_class", "pg_namespace", "pg_policies", "pg_proc", "information_schema",
  // CTE in messaging.service listConversations (#239).
  "my_recipients"]);

export function buildManifest() {
  const tables = new Map<string, Set<string>>();
  const functions = new Set<string>();
  for (const f of files(join(ROOT, "src"))) {
    const s = readFileSync(f, "utf8");
    for (const [re, priv] of PATTERNS) {
      for (const m of s.matchAll(re)) {
        const t = m[1];
        if (t.startsWith("app_") || NOT_TABLES.has(t)) continue;
        if (!tables.has(t)) tables.set(t, new Set());
        tables.get(t)!.add(priv);
      }
    }
    for (const m of s.matchAll(/\b(app_[a-z0-9_]+)\(/g)) functions.add(m[1]);
  }
  return {
    note: "Generated by scripts/generateRuntimePrivilegeManifest.ts. Candidate names; the startup check ignores names that are not tables or functions in the database.",
    tables: Object.fromEntries([...tables].sort(([a], [b]) => a.localeCompare(b)).map(([t, p]) => [t, [...p].sort()])),
    functions: [...functions].sort(),
  };
}

export const manifestText = () => JSON.stringify(buildManifest(), null, 2) + "\n";
export const MANIFEST_PATH = OUT;

if (process.argv[1]?.endsWith("generateRuntimePrivilegeManifest.ts")) {
  const text = manifestText();
  if (process.argv.includes("--check")) {
    if (readFileSync(OUT, "utf8") !== text) { console.error("runtimePrivileges.generated.json is out of date: run npx tsx scripts/generateRuntimePrivilegeManifest.ts"); process.exit(1); }
    console.log("runtime privilege manifest up to date");
  } else {
    writeFileSync(OUT, text);
    const m = JSON.parse(text) as { tables: object; functions: unknown[] };
    console.log(`wrote ${Object.keys(m.tables).length} tables, ${m.functions.length} functions`);
  }
}
